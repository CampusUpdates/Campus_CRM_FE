/**
 * Utility helper to get states list
 */
export const getIndianStates = (): string[] => {
  return INDIAN_STATES_AND_CITIES.map((s) => s.state);
};

/**
 * Utility helper to get cities by state name
 */
export const getCitiesByState = (stateName: string): string[] => {
  if (!stateName) return [];
  const stateObj = INDIAN_STATES_AND_CITIES.find(
    (s) => s.state.toLowerCase() === stateName.toLowerCase()
  );
  return stateObj ? stateObj.cities : [];
};
